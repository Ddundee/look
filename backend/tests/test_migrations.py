"""Migration safety: fresh installs, adopting pre-Alembic databases that hold
real Look data, downgrade/upgrade round trips, and model/migration drift.

Runs on SQLite always, and also on PostgreSQL when TEST_DATABASE_URL points
at a THROWAWAY database (CI does this). That database's public schema is
wiped at the start of every test here.
"""

import os
from datetime import date, datetime, time

import pytest
import sqlalchemy as sa
from alembic.util import AutogenerateDiffsDetected
from sqlmodel import Session, SQLModel

import app.models  # noqa: F401  (register every table)
from app import migrate as migrations
from app.models import Event, EventOverride, FoodEntry, NutritionTarget, RecurrenceRule, Task, User
from app.models.enums import MealType, RecurrencePattern, TaskPriority, TaskStatus

MODEL_TABLES = set(SQLModel.metadata.tables)
BASELINE_TABLES = set(migrations.baseline_schema())
CORE_TABLES = ["users", "recurrence_rules", "tasks"]

BACKENDS = [
    "sqlite",
    pytest.param(
        "postgres",
        marks=pytest.mark.skipif(
            not os.environ.get("TEST_DATABASE_URL"),
            reason="set TEST_DATABASE_URL to a throwaway PostgreSQL database to run these on Postgres",
        ),
    ),
]


@pytest.fixture(params=BACKENDS)
def db(request, tmp_path):
    if request.param == "sqlite":
        engine = sa.create_engine(f"sqlite:///{tmp_path / 'look.db'}")
    else:
        engine = sa.create_engine(os.environ["TEST_DATABASE_URL"])
        with engine.begin() as conn:
            conn.execute(sa.text("DROP SCHEMA public CASCADE"))
            conn.execute(sa.text("CREATE SCHEMA public"))
    yield engine
    engine.dispose()


# ---- realistic Look data --------------------------------------------------


def build_pre_alembic_db(engine, tables=None):
    """What every Look version before Alembic did at startup: create_all()
    over the models that existed then, i.e. the baseline's tables. (Models
    added later, like the LeetCode tables, never existed pre-Alembic.)"""
    names = tables or sorted(migrations.baseline_schema())
    SQLModel.metadata.create_all(engine, tables=[SQLModel.metadata.tables[t] for t in names])


